'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const yaml = require('js-yaml');
const version = require('../package.json').version;
const directory = process.argv[2] || 'dist';
const feed = yaml.load(fs.readFileSync(path.join(directory, 'latest.yml'), 'utf8'));
const expected = `Classic-Lyrics-Setup-${version}.exe`;
assert.equal(feed.version, version);
assert.equal(feed.path, expected);
assert.equal(feed.files.length, 1);
assert.equal(feed.files[0].url, expected);
const installer = fs.readFileSync(path.join(directory, expected));
const sha512 = createHash('sha512').update(installer).digest('base64');
assert.equal(feed.files[0].size, installer.length);
assert.equal(feed.files[0].sha512, sha512);
assert.equal(feed.sha512, sha512);
assert.ok(fs.statSync(path.join(directory, expected + '.blockmap')).size > 0);
console.log(`Verified ${version}: update filename, size, SHA-512 and blockmap.`);
